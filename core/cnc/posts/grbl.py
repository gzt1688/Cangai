"""GRBL 后置文件 —— 输出行为与 pymillcam 原 GrblPostProcessor 一致。

Grbl 1.1+（Arduino 雕刻机 / 3018 级 / grblHAL）。方言：
- G21 G90 G94 G17（程序头，可被机床宏覆盖）
- G0 / G1 每行重发（不省略 G 码）；F 模态（变化才输出）
- M3 S / M5；M8 / M9；T{n} M6；G4 P
"""
from __future__ import annotations

from .base import EnhancedGcodePost


class GrblPost(EnhancedGcodePost):
    name = "GRBL (Arduino 雕刻机)"
    description = "Grbl 1.1+ · 3018 级雕刻机 / 激光"
    controller = "grbl"

    # 与 pymillcam 现状一致：4 位删尾零、F 1 位删尾零
    coord_decimals = 4
    feed_decimals = 1
    arc_center_decimals = 4
    coord_strip_zeros = True
    feed_strip_zeros = True

    rapid_code = "G0"
    feed_code = "G1"
    arc_plane_code = None          # G17 在 program_start 中
    spindle_on = "M3 S{rpm}"
    spindle_off = "M5"
    coolant_on = "M8"
    coolant_off = "M9"
    dwell_code = "G4 P{dwell}"

    # 与 pymillcam 原 GrblPostProcessor 逐字一致
    program_start = "G21 G90"
    program_end = "M5\nM30"
    tool_change = "M5\nM0 (Change to T{tool_number})"
    header_comments = (
        "Generated by PyMillCAM - beta software",
        "Use at your own risk. Verify in a simulator before cutting.",
        "PyMillCAM authors are not liable for machine / workpiece damage or injury.",
    )

    # 与 pymillcam 现状一致：G 码/坐标每行重发，F 模态
    modal_g = False
    modal_xyz = False
    modal_f = True
    suppress_final_home = False

    line_ending = "\n"
